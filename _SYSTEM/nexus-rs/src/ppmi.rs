    #[test]
    fn expansion_map_tie_break_is_insertion_order() {
        // Construct three neighbors of "x" with EQUAL ppmi; the stable sort (NO lexical tiebreak)
        // must keep cooc-insertion order. Real-JS oracle: ["z","m","n"].
        // df all 2, N=4 → ppmi(x,*) all equal; cooc inserted x|z, m|x, n|x.
        let mut df: IndexMap<String, u64> = IndexMap::new();
        for t in ["x", "m", "n", "z"] {
            df.insert(t.into(), 2);
        }
        let mut cooc: IndexMap<String, u64> = IndexMap::new();
        cooc.insert(key("x", "z"), 2); // x<z → x|z
        cooc.insert(key("m", "x"), 2); // m<x → m|x
        cooc.insert(key("n", "x"), 2); // n<x → n|x
        let s = CoocStats { df, cooc, n: 4 };
        let map = build_expansion_map(&s, ExpansionOpts { min_cooc: 2, ppmi_floor: 0.0, top_n: 4 });
        assert_eq!(map.get("x").unwrap(), &vec!["z".to_string(), "m".to_string(), "n".to_string()]);
    }

