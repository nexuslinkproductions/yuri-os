//! nexus::ppmi — Rust port of the W4 "yuri-match matrix builds" from
//! `_SYSTEM/Scripts/math/yuri-token-expand.mjs` (+ `buildIdf` from `yuri-match-global-space.mjs`).
//!
//! Ported (Phase-2 deep wave, W4 GO set — matrix builds only):
//!   - `build_cooccurrence`  ← `buildCooccurrence`  [EXACT integer counts; structure-load-bearing]
//!   - `ppmi`                ← `ppmi`                [TRANSCENDENTAL log2; CAN return NaN at N=0]
//!   - `build_expansion_map` ← `buildExpansionMap`  [log2 + insertion-order tie-break, NO lexical tiebreak]
//!   - `build_idf`           ← `buildIdf`           [TRANSCENDENTAL log (natural) + V8 toFixed(12) round-trip]
//!
//! JS stays source-of-truth; this is delivery. Every vector pinned in `#[cfg(test)]` below was
//! generated by importing and CALLING the REAL JS function in node, never hand-computed (see the
//! oracle-command header in the test module).
//!
//! ── Conformance bar (00-MASTER-BRIEF §4/§5) ────────────────────────────────────────────────────
//! W4 yuri-match is **NOT gate-coupled** (advisory xref/circuitry/memory-match paths), so the bar
//! is the deck's general **1e-9 for floats** + EXACT for the integer/string structure. We TARGET and
//! ACHIEVE 0-ULP (bit-exact) on darwin-aarch64 anyway: V8 and the `libm` crate share the same fdlibm
//! fork there, so `libm::log2`/`libm::log` returned the *exact same bits* as V8 `Math.log2`/`Math.log`
//! for every pinned vector, and `format!("{:.12}")`+parse reproduced V8 `toFixed(12)→Number` exactly.
//!
//! ── Float-determinism discipline honored (00-MASTER-BRIEF §6/§6a) ───────────────────────────────
//!   - transcendentals via `libm::log2` / `libm::log` (pure-Rust fdlibm), NOT std method syntax.
//!   - f64 exclusively, no f32 paths; no `mul_add` — there is no `a*b+c` site in these kernels.
//!   - `-C target-feature=-fma` pinned crate-wide in `.cargo/config.toml`.
//!   - **`IndexMap` everywhere** (df / cooc / neigh) — V8 `Map` iterates in INSERTION order and that
//!     order is load-bearing: it drives `build_expansion_map`'s neighbor push order, and its stable
//!     sort has NO lexical tie-break, so equal-PPMI neighbors keep insertion order. Bare `HashMap`
//!     would scramble both. We replicate the JS exactly — we do NOT add a tiebreak (Phase-0 catch).
//!   - **NaN preserved, not guarded** — `ppmi` CAN return NaN at N=0 (`x/0` → NaN/Inf chains). The
//!     JS `Math.max(0, NaN)` returns NaN (Rust `f64::max` would return 0.0 → divergence), so we use
//!     a `js_max` that mirrors V8's NaN-propagating `Math.max` (Phase-0 catch).
//!   - **Co-occurrence key separator is `` (SOH, 0x01)**, not the empty string — the JS source
//!     renders it invisibly but it is `toks[i] + '' + toks[j]`. We use the same byte.
//!
//! ── Input contract (the tokenize boundary STAYS JS) ─────────────────────────────────────────────
//! `tokenize` (lowercase, split on `[^a-z0-9]+`, drop len<3, drop stop-words, 200k-char cap) is NOT
//! ported — it is a string kernel outside this matrix-build scope (see `staysJs`). `build_cooccurrence`
//! therefore takes **pre-tokenized** per-doc token arrays = the JS `[...tokenize(text)]` output
//! (insertion-ordered, de-duplicated by the Set). We replicate the in-function `.slice(0, cap).sort()`
//! and the `maxTokensPerDoc` clamp. Tokens are assumed to contain no `` byte (true for any
//! `tokenize` output, which is `[a-z0-9]` only) — a token containing `` would corrupt the key,
//! exactly as it would in the JS `key.split('')` round-trip in `build_expansion_map`.

use indexmap::IndexMap;

/// Co-occurrence key separator: V8 `Map` keys are `toks[i] + '' + toks[j]` (SOH, 0x01).
const COOC_SEP: char = '\u{0001}';

/// Co-occurrence statistics — mirror of the JS `{ df, cooc, N }` object.
/// `df`/`cooc` are `IndexMap` so iteration is INSERTION order, identical to V8 `Map`.
#[derive(Debug, Clone)]
pub struct CoocStats {
    /// term → document count (insertion order = first-seen order across docs, sorted-token order in-doc).
    pub df: IndexMap<String, u64>,
    /// "ab" (a < b within a doc's sorted tokens) → co-document count.
    pub cooc: IndexMap<String, u64>,
    /// document count.
    pub n: u64,
}

/// V8 `Math.max(0.0, x)` — NaN-PROPAGATING. `Math.max(0, NaN) === NaN`, whereas Rust `0.0.max(NaN)`
/// returns `0.0`. The PPMI `Math.max(0, log2(...))` must keep NaN, so we mirror V8 exactly.
#[inline]
fn js_max0(x: f64) -> f64 {
    if x.is_nan() {
        f64::NAN
    } else if x > 0.0 {
        x
    } else {
        0.0
    }
}

/// JS default `Array.prototype.sort()` for strings: compares by UTF-16 code unit, ascending, STABLE.
/// For `tokenize` output (`[a-z0-9]` ASCII only) this equals Rust's `str` `Ord` (UTF-8 byte order),
/// but we implement code-unit comparison so any pre-tokenized input is handled faithfully. V8's
/// default string sort is stable (ES2019+); `sort_by` is Rust's stable sort.
fn js_string_sort(tokens: &mut [String]) {
    tokens.sort_by(|a, b| {
        let mut ai = a.encode_utf16();
        let mut bi = b.encode_utf16();
        loop {
            match (ai.next(), bi.next()) {
                (Some(x), Some(y)) => {
                    if x != y {
                        return x.cmp(&y);
                    }
                }
                (None, Some(_)) => return std::cmp::Ordering::Less,
                (Some(_), None) => return std::cmp::Ordering::Greater,
                (None, None) => return std::cmp::Ordering::Equal,
            }
        }
    });
}

/// Resolve the `maxTokensPerDoc` cap exactly like the JS RED-TEAM clamp:
///   `Math.min(Number.isFinite(opt) && opt > 0 ? opt : 40, 200)`.
/// `None` / non-finite / ≤0 → default 40; any finite >0 value is `floor`ed implicitly by `.slice`
/// (JS `Array.prototype.slice` truncates a fractional length toward zero via ToIntegerOrInfinity).
fn resolve_cap(max_tokens_per_doc: Option<f64>) -> usize {
    let chosen = match max_tokens_per_doc {
        Some(v) if v.is_finite() && v > 0.0 => v,
        _ => 40.0,
    };
    // Math.min(chosen, 200)
    let capped = if chosen < 200.0 { chosen } else { 200.0 };
    // JS `.slice(0, len)` applies ToIntegerOrInfinity → truncate toward zero.
    capped.trunc() as usize
}

/// Port of `buildCooccurrence`. Takes **pre-tokenized** per-doc token arrays (the JS
/// `[...tokenize(text)]` output — insertion-ordered, de-duplicated). Replicates the in-function
/// `.slice(0, cap).sort()` and builds df + co-occurrence as insertion-ordered maps.
///
/// `max_tokens_per_doc` mirrors `opts.maxTokensPerDoc` (default 40, hard-clamped to 200).
pub fn build_cooccurrence(docs: &[Vec<String>], max_tokens_per_doc: Option<f64>) -> CoocStats {
    let cap = resolve_cap(max_tokens_per_doc);
    let mut df: IndexMap<String, u64> = IndexMap::new();
    let mut cooc: IndexMap<String, u64> = IndexMap::new();
    let n = docs.len() as u64;

    for doc in docs {
        // [...toks].slice(0, cap) — take the first `cap` tokens (insertion order preserved by caller).
        let take = doc.len().min(cap);
        let mut toks: Vec<String> = doc[..take].to_vec();
        // .sort() — JS default string sort (stable, UTF-16 code-unit order).
        js_string_sort(&mut toks);

        for i in 0..toks.len() {
            // df.set(toks[i], (df.get||0)+1)
            *df.entry(toks[i].clone()).or_insert(0) += 1;
            for j in (i + 1)..toks.len() {
                // key = toks[i] + '' + toks[j]  (toks already sorted → toks[i] <= toks[j])
                let mut key = String::with_capacity(toks[i].len() + 1 + toks[j].len());
                key.push_str(&toks[i]);
                key.push(COOC_SEP);
                key.push_str(&toks[j]);
                *cooc.entry(key).or_insert(0) += 1;
            }
        }
    }

    CoocStats { df, cooc, n }
}

/// Port of `ppmi(a, b, {df, cooc, N})`. PPMI(a,b) = max(0, log2[p(a,b)/(p(a)p(b))]).
///
/// EXACT replica of the JS branch structure, including its NaN behavior:
///   - `a === b` → 0
///   - `cooc.get(key) || 0`; `cab === 0` → 0  (also catches a missing key)
///   - `pa === 0 || pb === 0` → 0
///   - else `Math.max(0, Math.log2(pab / (pa * pb)))`
/// At N=0 with a present key, `pa = df/0` is NaN (0/0) or Inf, the `=== 0` guards are false, and the
/// final `Math.max(0, log2(...))` yields **NaN** — replicated, NOT guarded away (Phase-0 catch).
pub fn ppmi(a: &str, b: &str, stats: &CoocStats) -> f64 {
    if a == b {
        return 0.0;
    }
    // key = a < b ? a+SEP+b : b+SEP+a   — JS `<` is UTF-16 code-unit comparison.
    let key = build_cooc_key(a, b);
    let cab = *stats.cooc.get(&key).unwrap_or(&0); // cooc.get(key) || 0
    if cab == 0 {
        return 0.0;
    }
    let nf = stats.n as f64;
    let pa = (*stats.df.get(a).unwrap_or(&0) as f64) / nf; // (df.get(a)||0)/N
    let pb = (*stats.df.get(b).unwrap_or(&0) as f64) / nf;
    let pab = (cab as f64) / nf;
    if pa == 0.0 || pb == 0.0 {
        return 0.0;
    }
    js_max0(libm::log2(pab / (pa * pb)))
}

/// Build the `a < b ? a+SEP+b : b+SEP+a` co-occurrence key with V8 `<` (UTF-16 code-unit) semantics.
fn build_cooc_key(a: &str, b: &str) -> String {
    let (lo, hi) = if js_str_lt(a, b) { (a, b) } else { (b, a) };
    let mut key = String::with_capacity(lo.len() + 1 + hi.len());
    key.push_str(lo);
    key.push(COOC_SEP);
    key.push_str(hi);
    key
}

/// JS `a < b` for strings: UTF-16 code-unit lexicographic. Matches `js_string_sort`'s comparator.
fn js_str_lt(a: &str, b: &str) -> bool {
    let mut ai = a.encode_utf16();
    let mut bi = b.encode_utf16();
    loop {
        match (ai.next(), bi.next()) {
            (Some(x), Some(y)) => {
                if x != y {
                    return x < y;
                }
            }
            (None, Some(_)) => return true,  // a is a proper prefix of b → a < b
            (Some(_), None) => return false, // b is a proper prefix of a → a > b
            (None, None) => return false,    // equal → not <
        }
    }
}

/// Knobs for `build_expansion_map`, mirroring the JS destructured defaults
/// `{ minCooc = 3, ppmiFloor = 1.5, topN = 4 }`.
#[derive(Debug, Clone, Copy)]
pub struct ExpansionOpts {
    pub min_cooc: u64,
    pub ppmi_floor: f64,
    pub top_n: usize,
}

impl Default for ExpansionOpts {
    fn default() -> Self {
        ExpansionOpts { min_cooc: 3, ppmi_floor: 1.5, top_n: 4 }
    }
}

/// Port of `buildExpansionMap(stats, {minCooc, ppmiFloor, topN})`. term → top-N PPMI neighbors.
///
/// Replicates the JS exactly, including the **insertion-order tie-break with NO lexical tiebreak**
/// (Phase-0 catch): the comparator is purely `(x, y) => y.s - x.s`, and V8's `Array.sort` is stable,
/// so neighbors with equal PPMI keep the order in which they were pushed — which follows the `cooc`
/// IndexMap iteration (insertion) order. We do NOT add a lexical tiebreak.
///
/// The JS `arr.sort((x, y) => y.s - x.s)` treats a NaN comparator return as 0 (no reorder); our
/// stable sort with an `Equal` fallback on non-orderable pairs reproduces that "leave in place".
pub fn build_expansion_map(stats: &CoocStats, opts: ExpansionOpts) -> IndexMap<String, Vec<String>> {
    // neigh: term → [(neighborTerm, ppmiScore)] in push order.
    let mut neigh: IndexMap<String, Vec<(String, f64)>> = IndexMap::new();

    for (key, &c) in &stats.cooc {
        if c < opts.min_cooc {
            continue;
        }
        // const [a, b] = key.split('')  — split on the SOH separator, take first two parts.
        let mut parts = key.splitn(2, COOC_SEP);
        let a = parts.next().unwrap_or("");
        let b = parts.next().unwrap_or("");
        let s = ppmi(a, b, stats);
        // if (s < ppmiFloor) continue;   — note: NaN < x is false in JS too, so a NaN s is NOT skipped.
        if s < opts.ppmi_floor {
            continue;
        }
        // neigh(a).push({t:b,s}); neigh(b).push({t:a,s});
        neigh.entry(a.to_string()).or_default().push((b.to_string(), s));
        neigh.entry(b.to_string()).or_default().push((a.to_string(), s));
    }

    let mut map: IndexMap<String, Vec<String>> = IndexMap::new();
    for (term, arr) in &neigh {
        let mut sorted = arr.clone();
        // arr.sort((x, y) => y.s - x.s)  — descending by score, STABLE, no lexical tiebreak.
        // JS: a positive return swaps; equal/NaN return leaves order. We map (y.s - x.s) sign:
        //   y.s > x.s → positive → x after y → x is "Greater". So compare y vs x = x.s.cmp_desc.
        sorted.sort_by(|x, y| {
            // descending: y.s before x.s when y.s > x.s. Equivalent to comparing x.s and y.s desc.
            // total order that mirrors `y.s - x.s` sign with NaN→Equal (leave in place).
            match (y.1 - x.1).partial_cmp(&0.0) {
                Some(ord) => ord,
                None => std::cmp::Ordering::Equal, // NaN diff → JS treats as 0 → no reorder
            }
        });
        let out: Vec<String> = sorted.into_iter().take(opts.top_n).map(|(t, _)| t).collect();
        map.insert(term.clone(), out);
    }
    map
}

/// Port of `buildIdf`'s scoring line from `yuri-match-global-space.mjs`:
///   `idf.set(feature, Number((Math.log((1 + N) / (1 + count)) + 1).toFixed(12)))`
///
/// The `featureFn`/`tokenize`-driven df accumulation STAYS JS (string kernel out of scope); this takes
/// the **pre-computed** df entries (insertion order) + N and produces the idf map. Float bar: 1e-9
/// (W4 non-gate-coupled), but we reproduce V8 `Number(x.toFixed(12))` BIT-EXACT via `format!("{:.12}")`
/// + parse — verified equal on every pinned vector (incl. the round-half-to-even `toFixed` case).
pub fn build_idf(df_entries: &[(String, u64)], n: u64) -> IndexMap<String, f64> {
    let mut idf: IndexMap<String, f64> = IndexMap::new();
    let nf = n as f64;
    for (feature, count) in df_entries {
        // Math.log((1+N)/(1+count)) + 1   — natural log via libm.
        let raw = libm::log((1.0 + nf) / (1.0 + *count as f64)) + 1.0;
        idf.insert(feature.clone(), to_fixed_12_number(raw));
    }
    idf
}

/// V8 `Number(value.toFixed(12))`: format to 12 fractional decimal digits (round-half-to-even on the
/// underlying f64, like V8), then parse back (shortest-round-trip, like `Number(...)`).
///
/// `toFixed` is only defined for finite values with magnitude < 1e21; the idf inputs are always small
/// finite numbers, so the simple `format!("{:.12}")` path matches V8 exactly (verified). For a
/// non-finite input we return it unchanged (V8 `toFixed` would throw / "NaN"; idf never feeds one).
fn to_fixed_12_number(value: f64) -> f64 {
    if !value.is_finite() {
        return value;
    }
    let s = format!("{:.12}", value);
    s.parse::<f64>().unwrap_or(value)
}

