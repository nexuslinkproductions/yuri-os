    #[test]
    fn idf_pins() {
        // D_IDF_N5 = [["auth",1.182321556794],["login",1.69314718056],
        //             ["dangling",2.098612288668],["x",2.791759469228]]
        let df = vec![
            ("auth".to_string(), 4u64),
            ("login".to_string(), 2),
            ("dangling".to_string(), 1),
            ("x".to_string(), 0),
        ];
        let idf = build_idf(&df, 5);
        close(*idf.get("auth").unwrap(), 1.182321556794);
        close(*idf.get("login").unwrap(), 1.69314718056);
        close(*idf.get("dangling").unwrap(), 2.098612288668);
        close(*idf.get("x").unwrap(), 2.791759469228);
        // insertion order preserved
        let keys: Vec<&str> = idf.keys().map(|k| k.as_str()).collect();
        assert_eq!(keys, vec!["auth", "login", "dangling", "x"]);
    }

    #[test]
    fn idf_more_pins() {
        // D_IDF_N100 = [["a",4.921973336281],["b",1.683294884117],["c",1]]
        let idf = build_idf(
            &[("a".to_string(), 1u64), ("b".to_string(), 50), ("c".to_string(), 100)],
            100,
        );
        close(*idf.get("a").unwrap(), 4.921973336281);
        close(*idf.get("b").unwrap(), 1.683294884117); // the round-half-to-even toFixed case
        close(*idf.get("c").unwrap(), 1.0);
        // D_IDF_countGTn = [["x",-0.29928298413]]  (count > N → negative idf)
        let idf2 = build_idf(&[("x".to_string(), 10u64)], 2);
        close(*idf2.get("x").unwrap(), -0.29928298413);
        // D_IDF_N0 = [["x",1]]  (N=0, count=0 → log(1/1)+1 = 1)
        let idf3 = build_idf(&[("x".to_string(), 0u64)], 0);
        close(*idf3.get("x").unwrap(), 1.0);
    }

