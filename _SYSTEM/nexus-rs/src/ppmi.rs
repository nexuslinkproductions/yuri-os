    #[test]
    fn js_string_sort_matches_default_sort() {
        // JS default Array.sort() string order is stable, code-unit ascending.
        let mut v: Vec<String> = ["zebra", "yankee", "xray"].iter().map(|s| s.to_string()).collect();
        js_string_sort(&mut v);
        assert_eq!(v, vec!["xray".to_string(), "yankee".to_string(), "zebra".to_string()]);
        // numerics sort before letters by code unit ('0'..'9' < 'a'..'z')
        let mut v2: Vec<String> = ["b2", "a1", "10", "9z"].iter().map(|s| s.to_string()).collect();
        js_string_sort(&mut v2);
        assert_eq!(v2, vec!["10".to_string(), "9z".to_string(), "a1".to_string(), "b2".to_string()]);
    }
