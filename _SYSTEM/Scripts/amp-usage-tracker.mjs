#!/usr/bin/env node
/**
 * amp-usage-tracker.mjs
 * Polls `amp usage` + `amp threads list`, writes a dated Markdown note
 * to _SYSTEM/amp-usage-log.md in the Obsidian vault.
 *
 * Usage:
 *   node _SYSTEM/Scripts/amp-usage-tracker.mjs          # write/update log
 *   node _SYSTEM/Scripts/amp-usage-tracker.mjs --print  # stdout only, no write
 */

import { execSync } from 'child_process';
import { writeFileSync, readFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const LOG_PATH = join(ROOT, '_SYSTEM', 'amp-usage-log.md');
const PRINT_ONLY = process.argv.includes('--print');

function run(cmd) {
  try {
    return execSync(cmd, {
      env: { ...process.env },
      cwd: ROOT,
      timeout: 15000,
    }).toString().trim();
  } catch (e) {
    return `[error: ${e.message.split('\n')[0]}]`;
  }
}

const now = new Date();
const dateStr = now.toISOString().slice(0, 10);
const timeStr = now.toTimeString().slice(0, 8);

const usage   = run('amp usage');
const threads = run('amp threads list');

// Parse credit line: "Individual credits: $X remaining"
const creditMatch = usage.match(/\$([0-9.]+)\s+remaining/);
const credits = creditMatch ? `$${creditMatch[1]}` : 'unknown';

// Count threads
const threadLines = threads.split('\n').filter(l => l.trim() && !l.startsWith('No threads'));
const threadCount = threadLines.length;

const entry = `
## ${dateStr} ${timeStr}

| Field | Value |
|---|---|
| Credits remaining | ${credits} |
| Active threads | ${threadCount} |
| MCP servers | obsidianMcpTools, obsidianVault, gitnexus |

\`\`\`
${usage}
\`\`\`

<details><summary>Threads</summary>

\`\`\`
${threads || 'none'}
\`\`\`

</details>
`;

if (PRINT_ONLY) {
  process.stdout.write(entry);
  process.exit(0);
}

// Append to log (create if missing)
const header = `# Amp Usage Log\n\nAuto-generated by _SYSTEM/Scripts/amp-usage-tracker.mjs\n`;
let existing = existsSync(LOG_PATH) ? readFileSync(LOG_PATH, 'utf8') : header;
// Prepend new entry after header block
const headerEnd = existing.indexOf('\n## ');
if (headerEnd === -1) {
  existing = existing + entry;
} else {
  existing = existing.slice(0, headerEnd) + entry + existing.slice(headerEnd);
}
writeFileSync(LOG_PATH, existing);
process.stdout.write(`[amp-tracker] ${dateStr} ${timeStr} — ${credits} remaining, ${threadCount} threads → ${LOG_PATH}\n`);
