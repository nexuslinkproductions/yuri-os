/**
 * Write `content` to `filePath` atomically (tmpfile + rename). The caller is
 * responsible for ensuring `dirname(filePath)` already exists — in `sync()`
 * this is done via `ensureDirTracked()` BEFORE staging so every directory
 * this transaction creates is tracked for precise rollback. This function
 * intentionally does NOT create directories itself; an untracked mkdir here
 * would let an absent parent (e.g. `_SYSTEM/state`) silently survive a
 * rolled-back transaction.
 */
function atomicWrite(filePath, content) {
  const dir = dirname(filePath);
  const tmpFile = resolve(dir, `.tmp-${randomUUID()}`);
  writeFileSync(tmpFile, content, 'utf-8');
  renameSync(tmpFile, filePath);
}

/** Normalize CRLF to LF so Windows-authored or accidentally-CRLF files never
 *  cause false ownership/drift mismatches against LF-rendered output. */
function normalizeCRLF(content) {
  return content == null ? content : content.replace(/\r\n/g, '\n');
}

/**
 * Strict read: ENOENT is the ONLY error treated as "absent" (returns null).
 * Any other error (EISDIR, EACCES, ELOOP, …) is a contextual SyncError raised
 * BEFORE any mutation — an unreadable target must never be silently skipped
 * or silently overwritten.
 */
function tryReadStrict(filePath, label) {
  let raw;
  try {
    raw = readFileSync(filePath, 'utf-8');
  } catch (err) {
    if (err && err.code === 'ENOENT') return null;
    throw new SyncError(
      `Cannot read ${label} at ${filePath}: ${err && err.code ? err.code : (err && err.message) || err}`,
      { filePath, label, code: err && err.code });
  }
  return normalizeCRLF(raw);
}

/**
 * Reject symlinked output roots, path components, and targets, and reject
 * any canonical parent that resolves outside the repo root. Walks every path
 * segment from `repoRoot` down to `targetPath`; the first symlinked segment
 * (root, intermediate directory, or the target itself) aborts with a
 * SyncError before any staging or mutation occurs. Segments that do not yet
 * exist are skipped (nothing to reject) — they will be created fresh.
 *
 * After the per-component walk finds zero symlinks below `repoRoot`, it
 * ALSO resolves the nearest existing ancestor of `targetPath` to its
 * canonical (symlink-resolved) path and requires that to fall under the
 * canonical repo root — catching the case where `repoRoot`'s own on-disk
 * location is itself reached through a symlink from outside the caller's
 * view, which a walk confined to segments below `repoRoot` cannot detect
 * on its own.
 *
 * `repoRoot` defaults to this module's own {@link REPO_ROOT} (every
 * internal `sync()`/`check()` call site relies on that default and never
 * passes it explicitly). It is exported and overridable so a consumer
 * running its own fixtures under a DIFFERENT root (e.g. a validator's
 * temp-directory harness that imports this module but never mutates the
 * module-level `REPO_ROOT` it closed over) can reuse the exact same
 * symlink-safety and canonical-containment logic against ITS root instead.
 */
export function assertPathChainSafe(targetPath, label, repoRoot = REPO_ROOT) {
  const root = resolve(repoRoot);
  const rootReal = root === REPO_ROOT
    ? REPO_ROOT_REAL
    : (() => { try { return realpathSync(root); } catch { return root; } })();

  const rel = relative(root, targetPath);
  if (rel === '' || rel.startsWith(`..${sep}`) || rel === '..' || isAbsolute(rel)) {
    throw new SyncError(`${label} resolves outside the repository root`, { targetPath, label });
  }
  const segments = rel.split(sep);
  let current = root;
  let nearestExisting = root;
  for (const seg of segments) {
    current = resolve(current, seg);
    let st;
    try {
      st = lstatSync(current);
    } catch (err) {
      if (err && err.code === 'ENOENT') continue;
      throw new SyncError(
        `Cannot stat path component for ${label}: ${current} (${err && err.code ? err.code : (err && err.message) || err})`,
        { current, label, code: err && err.code });
    }
    if (st.isSymbolicLink()) {
      throw new SyncError(
        `${label} path component is a symlink: ${current} — refusing to follow symlinked ` +
        `output roots, components, or targets.`,
        { current, label });
    }
    nearestExisting = current; // exists, confirmed not a symlink
  }

  let nearestExistingReal;
  try {
    nearestExistingReal = realpathSync(nearestExisting);
  } catch (err) {
    throw new SyncError(
      `Cannot resolve canonical path for ${label}: ${nearestExisting} (${err && err.code ? err.code : (err && err.message) || err})`,
      { nearestExisting, label, code: err && err.code });
  }
  if (nearestExistingReal !== rootReal && !nearestExistingReal.startsWith(rootReal + sep)) {
    throw new SyncError(
      `${label} canonical parent resolves outside the repository root: ${nearestExistingReal}`,
      { targetPath, label, nearestExistingReal, repoRootReal: rootReal });
  }
}

/**
 * Structural ownership check: line 1 must be exactly "---" and line 2 must
 * be exactly the short or long generator marker (see {@link AGENT_MARKER_SHORT}
 * / {@link AGENT_MARKER_LONG}). A card that mentions the marker in body or a
 * later comment still fails this gate. CRLF-normalized before comparison.
 */
export function isOwnedAgentFile(content) {
  if (!content) return false;
  const lines = normalizeCRLF(content).split('\n');
  return lines[0] === '---' && (lines[1] === AGENT_MARKER_SHORT || lines[1] === AGENT_MARKER_LONG);
}

/** Config ownership: first line must be the short or long generator marker. */
export function isOwnedConfig(content) {
  if (!content) return false;
  const firstLine = normalizeCRLF(content).split('\n')[0];
  return firstLine === CONFIG_MARKER_SHORT || firstLine === CONFIG_MARKER_LONG;
}

/**
 * Manifest ownership: must parse as JSON and carry `_provenance` equal to
 * {@link MANIFEST_MARKER}. A pre-marker manifest (predating provenance
 * tracking) is NOT accepted — it must be removed to let the generator own it.
 */
export function isOwnedManifest(content) {
  if (!content) return false;
  let parsed;
  try {
    parsed = JSON.parse(normalizeCRLF(content));
  } catch {
    return false;
  }
  return !!parsed && typeof parsed === 'object' && parsed._provenance === MANIFEST_MARKER;
}

// ---------------------------------------------------------------------------
// Sync (write mode) — staged transaction with rollback
// ---------------------------------------------------------------------------
//
// Phases:
//   1. Preflight    — symlink-safety on every output root/component/target,
//                      strict reads, and ownership checks. No mutation.
//   2. Ensure dirs   — create every missing parent directory (agents/, and,
//                      independently, config's and the manifest's parents)
//                      one component at a time, tracked for precise
//                      rollback removal.
//   3. Stage         — for every replacement (card/config/manifest) AND
//                      every stale owned card: move any existing bytes
//                      aside into a same-parent hidden sibling backup
//                      (never an os.tmpdir() path, so the rename is always
//                      same-filesystem — no EXDEV risk — and the backup
//                      filename never ends in ".md", so it stays
//                      undiscoverable to the ".md" scans used by stale
//                      cleanup and --check). A stale target's staging IS
//                      its removal — no further write follows it.
//   4. Commit        — write the new content for every replacement target
//                      (cards, config, manifest), in order. A deterministic
//                      test-only fault-injection hook can throw immediately
//                      after any Nth commit (see testFaultInjectionThreshold).
//   5. On failure    — restore every prior byte (and every stale card) from
//                      its sibling backup, remove every directory this
//                      transaction created (deepest-first, only if now
//                      empty), and re-throw a contextual SyncError.
//   6. On success    — delete every sibling backup file. Backups are
//                      deleted ONLY after the full transaction succeeds.

/**
 * TEST-ONLY deterministic fault injection. Inert unless the env var is set
 * (never touched by any production invocation): when set to a positive
 * integer N, the staged transaction throws a synthetic error immediately
 * after its Nth commit completes and before the (N+1)th begins — exercising
 * the exact same catch/rollback path a real filesystem failure would,
 * without depending on filesystem permissions (which a privileged/root test
 * runner can silently bypass, making a chmod-based "injected failure" pass
 * trivially without ever exercising the failure path). Never alters output;
 * it only ever throws, so a stray env var can never silently corrupt a real
 * sync — worst case is a loud, clearly-labeled failure.
 */
function testFaultInjectionThreshold() {
  const raw = process.env.MURE_OMP_SYNC_TEST_FAIL_AFTER_COMMIT;
  if (!raw) return null;
  const n = Number(raw);
  return Number.isInteger(n) && n > 0 ? n : null;
}

function sync(projection, sourceGenerated) {
  const generatedFilenames = new Set(projection.cards.map(c => `${c.filename}.md`));
  // --- Phase 1a: symlink/root safety for the three output roots ----------
  assertPathChainSafe(AGENTS_DIR, '.omp/agents');
  assertPathChainSafe(CONFIG_PATH, '.omp/config.yml');
  assertPathChainSafe(MANIFEST_PATH, '_SYSTEM/state/mure-omp-projection.json');

  const cardTargets = projection.cards.map(card => {
    const filePath = resolve(AGENTS_DIR, `${card.filename}.md`);
    return { kind: 'card', label: `.omp/agents/${card.filename}.md`, filePath, content: renderOmpAgent(card) };
  });
  const configTarget = { kind: 'config', label: '.omp/config.yml', filePath: CONFIG_PATH, content: renderProjectConfig(projection) };
  const manifestTarget = { kind: 'manifest', label: '_SYSTEM/state/mure-omp-projection.json', filePath: MANIFEST_PATH, content: renderProjectionManifest(projection, sourceGenerated) };

  for (const t of cardTargets) {
    assertPathChainSafe(t.filePath, t.label);
  }

  // --- Phase 1b: strict reads + ownership preflight — no mutation yet ----
  for (const t of cardTargets) {
    const existing = tryReadStrict(t.filePath, t.label);
    if (existing !== null && !isOwnedAgentFile(existing)) {
      throw new SyncError(
        `Refusing to overwrite ${t.label}: line 1 is not "---" or line 2 is not a recognized ` +
        `generator marker.\n` +
        `The file appears hand-authored. Add the canonical marker as the first YAML comment ` +
        `or remove the file to let the generator own it.`,
        { filePath: t.filePath }
      );
    }
  }

  const existingConfig = tryReadStrict(configTarget.filePath, configTarget.label);
  if (existingConfig !== null && !isOwnedConfig(existingConfig)) {
    throw new SyncError(
      `Refusing to overwrite .omp/config.yml: first line is not a recognized generator marker.\n` +
      `The config is user-owned. Add the generator marker as line 1 or remove the file to let the generator own it.`,
      { configPath: configTarget.filePath }
    );
  }

  const existingManifest = tryReadStrict(manifestTarget.filePath, manifestTarget.label);
  if (existingManifest !== null && !isOwnedManifest(existingManifest)) {
    throw new SyncError(
      `Refusing to overwrite ${manifestTarget.label}: missing provenance marker ` +
      `"${MANIFEST_MARKER}".\nThe manifest appears hand-authored, or predates provenance ` +
      `tracking. Remove it to let the generator own it again.`,
      { manifestPath: manifestTarget.filePath }
    );
  }

  // --- Stale cleanup candidates: structurally owned agent files not in the
  //     current projection. Computed during preflight (strict reads +
  //     symlink safety on every entry) but only removed during commit.
  //     AGENTS_DIR is intentionally NOT created here — creating it is a
  //     mutation, and every fallible preflight check (including this stale
  //     scan) must complete before the first mutation happens. If the
  //     directory does not yet exist there are structurally zero stale
  //     candidates to find.
  const staleTargets = [];
  if (existsSync(AGENTS_DIR)) {
    for (const entry of readdirSync(AGENTS_DIR)) {
      if (!entry.endsWith('.md')) continue;
      if (generatedFilenames.has(entry)) continue;
      const filePath = resolve(AGENTS_DIR, entry);
      assertPathChainSafe(filePath, `.omp/agents/${entry}`);
      const content = tryReadStrict(filePath, `.omp/agents/${entry}`);
      if (isOwnedAgentFile(content)) {
        staleTargets.push({ kind: 'stale', label: `.omp/agents/${entry}`, filePath, content: null });
      }
    }
  }

  // --- Phase 2/3/4: staged transaction with rollback ----------------------
  // Backups are same-parent hidden siblings of each target (never an
  // os.tmpdir() path) so the stage-then-commit rename is always same-
  // filesystem — cross-device (EXDEV) rename failures would otherwise
  // silently defeat the transaction before commit even runs. The backup
  // filename never ends in ".md", so AGENTS_DIR's `.endsWith('.md')` scan
  // (stale cleanup, --check) can never discover a card backup as an extra.
  const restoreLog = [];
  // Every directory THIS transaction creates (agents/, and — if absent —
  // any missing ancestor up to and including .omp itself, or _SYSTEM/state
  // for the manifest), in creation order (shallowest first per chain). On
  // rollback these are removed in reverse order (deepest first) so a
  // partially-populated tree never orphans a still-needed parent, and a
  // directory that already existed before this transaction is NEVER queued
  // here, so it can never be removed.
  const createdDirs = [];

  function backupSiblingPath(filePath) {
    return join(dirname(filePath), `.mure-omp-sync.bak-${randomUUID()}`);
  }

  /**
   * Create `dir` and every missing ancestor, one path component at a time,
   * recording each newly-created directory in `createdDirs`. A no-op for any
   * directory that already exists. Never uses `{recursive: true}` — creating
   * one level at a time is what makes precise, ownership-scoped rollback
   * possible (only directories WE created are ever queued for removal).
   */
  function ensureDirTracked(dir) {
    const toCreate = [];
    let current = dir;
    while (!existsSync(current)) {
      toCreate.push(current);
      const parent = dirname(current);
      if (parent === current) break; // filesystem root safety net
      current = parent;
    }
    toCreate.reverse(); // shallowest missing ancestor first
    for (const d of toCreate) {
      mkdirSync(d);
      createdDirs.push(d);
    }
  }

  function rollback() {
    for (const entry of restoreLog) {
      if (existsSync(entry.filePath)) {
        try { rmSync(entry.filePath, { recursive: true, force: true }); } catch { /* best-effort */ }
      }
      if (entry.existed) {
        renameSync(entry.backupPath, entry.filePath);
      }
    }
    // Remove directories THIS transaction created, deepest-first. rmdirSync
    // atomically fails (ENOTEMPTY) instead of deleting anything if content
    // landed there after our emptiness expectation — in that case we stop
    // walking that chain (its ancestors are non-empty too) rather than risk
    // a recursive delete of data this transaction never touched.
    for (let i = createdDirs.length - 1; i >= 0; i--) {
      const dir = createdDirs[i];
      if (!existsSync(dir)) continue;
      try {
        rmdirSync(dir);
      } catch {
        break;
      }
    }
  }

  try {
    // Phase A: ensure every unique parent directory this transaction may
    // need to write into exists (tracked for precise rollback removal).
    // agents/ always exists after a successful sync, even for a 0-card
    // catalog — matches the external validator's config/state-implies-
    // agents-dir invariant. config's and the manifest's parents may each
    // independently be absent on a first sync.
    ensureDirTracked(AGENTS_DIR);
    ensureDirTracked(dirname(configTarget.filePath));
    ensureDirTracked(dirname(manifestTarget.filePath));

    const allTargets = [...cardTargets, configTarget, manifestTarget, ...staleTargets];

    // Phase B: stage EVERY card/config/manifest replacement and EVERY
    // stale owned card — move existing bytes aside into a non-discoverable
    // same-parent backup (or record that nothing existed yet). No writes
    // happen in this phase; a stale target's staging IS its removal.
    for (const t of allTargets) {
      if (existsSync(t.filePath)) {
        const backupPath = backupSiblingPath(t.filePath);
        renameSync(t.filePath, backupPath);
        restoreLog.push({ filePath: t.filePath, backupPath, existed: true });
      } else {
        restoreLog.push({ filePath: t.filePath, backupPath: null, existed: false });
      }
    }

    // Phase C: commit every replacement target (stale cards were already
    // fully committed by phase B's staging — a removal has no further
    // write step).
    const testFailAfterCommit = testFaultInjectionThreshold();
    let committedCount = 0;
    for (const t of allTargets) {
      if (t.kind !== 'stale') {
        atomicWrite(t.filePath, t.content);
      }
      committedCount++;
      if (testFailAfterCommit !== null && committedCount === testFailAfterCommit) {
        throw new Error(
          `[deterministic test fault injection] MURE_OMP_SYNC_TEST_FAIL_AFTER_COMMIT=` +
          `${testFailAfterCommit} reached after committing "${t.label}"`
        );
      }
    }

    // Whole transaction succeeded — clean stages: delete every backup file.
    for (const entry of restoreLog) {
      if (entry.existed) {
        try { rmSync(entry.backupPath, { force: true }); } catch { /* best-effort */ }
      }
    }
  } catch (err) {
    rollback();
    if (err instanceof SyncError) throw err;
    throw new SyncError(
      `Sync commit failed and was rolled back: ${err && err.message ? err.message : err}`,
      { cause: String((err && err.message) || err) }
    );
  }

  return {
    written: projection.cards.length,
    agentsDir: AGENTS_DIR,
    configPath: CONFIG_PATH,
    manifestPath: MANIFEST_PATH,
    executable: projection.executable,
    disabled: projection.disabled,
  };
}

// ---------------------------------------------------------------------------
// Check (drift detection, read-only)
// ---------------------------------------------------------------------------

function check(projection, sourceGenerated) {
  const issues = [];

  assertPathChainSafe(AGENTS_DIR, '.omp/agents');
  assertPathChainSafe(CONFIG_PATH, '.omp/config.yml');
  assertPathChainSafe(MANIFEST_PATH, '_SYSTEM/state/mure-omp-projection.json');

  // Build expected content for all projected agent files
  const expectedAgents = new Map();
  for (const card of projection.cards) {
    const rendered = renderOmpAgent(card);
    expectedAgents.set(`${card.filename}.md`, rendered);
  }

  // Check agents directory
  if (existsSync(AGENTS_DIR)) {
    const onDisk = new Set();
    for (const entry of readdirSync(AGENTS_DIR)) {
      if (!entry.endsWith('.md')) continue;
      onDisk.add(entry);

      const filePath = resolve(AGENTS_DIR, entry);
      assertPathChainSafe(filePath, `.omp/agents/${entry}`);
      const content = tryReadStrict(filePath, `.omp/agents/${entry}`);

      // Every non-projected .md file is reported, owned or not — sync never
      // deletes an unowned extra, so --check must never hide one either.
      if (!expectedAgents.has(entry)) {
        const owned = isOwnedAgentFile(content);
        issues.push({
          type: owned ? 'extra_agent' : 'extra_agent_unowned',
          file: `.omp/agents/${entry}`,
          detail: owned
            ? 'owned file not in projection'
            : 'unowned extra file present — sync will never delete it',
        });
        continue;
      }

      // Expected file — check ownership, then compare content
      const expected = expectedAgents.get(entry);
      if (content === null) {
        issues.push({ type: 'missing_agent', file: `.omp/agents/${entry}`, detail: 'expected file cannot be read' });
      } else if (!isOwnedAgentFile(content)) {
        issues.push({ type: 'agent_not_owned', file: `.omp/agents/${entry}`, detail: 'expected file is not structurally owned; would refuse overwrite' });
      } else if (content !== expected) {
        issues.push({ type: 'agent_content_drift', file: `.omp/agents/${entry}`, detail: 'content differs from projection' });
      }
    }

    // Check for files we expect that aren't on disk at all
    for (const [filename] of expectedAgents) {
      if (!onDisk.has(filename)) {
        issues.push({ type: 'missing_agent', file: `.omp/agents/${filename}`, detail: 'expected file is absent' });
      }
    }
  } else if (expectedAgents.size > 0) {
    for (const [filename] of expectedAgents) {
      issues.push({ type: 'missing_agent', file: `.omp/agents/${filename}`, detail: 'agents directory does not exist' });
    }
  }

  // Check config.yml
  const existingConfig = tryReadStrict(CONFIG_PATH, '.omp/config.yml');
  const expectedConfig = renderProjectConfig(projection);
  if (existingConfig !== null) {
    if (!isOwnedConfig(existingConfig)) {
      issues.push({ type: 'config_not_owned', file: '.omp/config.yml', detail: 'first line is not a recognized generator marker; would refuse overwrite' });
    } else if (existingConfig !== expectedConfig) {
      issues.push({ type: 'config_content_drift', file: '.omp/config.yml', detail: 'content differs from projection' });
    }
  } else {
    issues.push({ type: 'missing_config', file: '.omp/config.yml', detail: 'config file does not exist' });
  }

  // Check manifest
  const existingManifest = tryReadStrict(MANIFEST_PATH, '_SYSTEM/state/mure-omp-projection.json');
  const expectedManifest = renderProjectionManifest(projection, sourceGenerated);
  if (existingManifest !== null) {
    if (!isOwnedManifest(existingManifest)) {
      issues.push({ type: 'manifest_not_owned', file: '_SYSTEM/state/mure-omp-projection.json', detail: 'missing provenance marker; would refuse overwrite' });
    } else if (existingManifest !== expectedManifest) {
      issues.push({ type: 'manifest_content_drift', file: '_SYSTEM/state/mure-omp-projection.json', detail: 'content differs from projection' });
    }
  } else {
    issues.push({ type: 'missing_manifest', file: '_SYSTEM/state/mure-omp-projection.json', detail: 'manifest file does not exist' });
  }

  return {
    ok: issues.length === 0,
    issues,
    executable: projection.executable,
    disabled: projection.disabled,
  };
 }

// ---------------------------------------------------------------------------
// CLI entry point
// ---------------------------------------------------------------------------

function main() {
  const mode = process.argv[2] || 'sync';

  let catalog;
  try {
    catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf-8'));
  } catch (err) {
    console.error(`ERROR: Cannot read catalog at ${CATALOG_PATH}: ${err.message}`);
    process.exit(1);
  }

  if (!Array.isArray(catalog.agents)) {
    console.error('ERROR: Catalog is missing "agents" array.');
    process.exit(1);
  }

  let projection;
  try {
    projection = buildOmpProjection(catalog);
  } catch (err) {
    if (err instanceof SyncError) {
      console.error(`VALIDATION ERROR: ${err.message}`);
      if (err.details) console.error('  Details:', JSON.stringify(err.details));
      process.exit(1);
    }
    throw err;
  }

  const sourceGenerated = catalog.generated ?? null;
  const { cards, executable, disabled } = projection;
  const total = cards.length;

  if (mode === '--check') {
    let result;
    try {
      result = check(projection, sourceGenerated);
    } catch (err) {
      if (err instanceof SyncError) {
        console.error(`CHECK ERROR: ${err.message}`);
        if (err.details) console.error('  Details:', JSON.stringify(err.details));
        process.exit(1);
      }
      throw err;
    }
    if (result.ok) {
      console.log(`OK: ${total} projected (${executable} executable, ${disabled} disabled) — no drift detected.`);
      process.exit(0);
    }
    console.log(`DRIFT: ${total} projected (${executable} executable, ${disabled} disabled) — ${result.issues.length} issue(s):`);
    for (const issue of result.issues) {
      console.log(`  [${issue.type}] ${issue.file}: ${issue.detail}`);
    }
    process.exit(1);
  }

  // Sync mode
  try {
    const result = sync(projection, sourceGenerated);
    console.log(`Synced: ${result.written} cards → ${result.agentsDir}`);
    console.log(`  ${result.executable} executable, ${result.disabled} disabled`);
    console.log(`  Config: ${result.configPath}`);
    console.log(`  Manifest: ${result.manifestPath}`);
  } catch (err) {
    if (err instanceof SyncError) {
      console.error(`SYNC ERROR: ${err.message}`);
      process.exit(1);
    }
    throw err;
  }
}

