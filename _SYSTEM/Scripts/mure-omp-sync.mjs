class SyncError extends Error {
  constructor(message, details = {}) {
    super(message);
    this.name = 'SyncError';
    this.details = details;
  }
}

function assert(condition, message, details) {
  if (!condition) throw new SyncError(message, details);
}

/** Assert that, when present, `value` is an Array — guards every array the projector consumes. */
function assertOptionalArray(value, fieldName, agentName) {
  if (value === undefined || value === null) return;
  assert(Array.isArray(value),
    `Field "${fieldName}" of agent "${agentName}" must be an array, got ${typeof value}`,
    { agentName, fieldName, value });
}

/**
 * Validate a pending-variant array (either the live `pending_variants` key or
 * the legacy `pendingVariants` key). Shape-checked but never resolved into a
 * card — see the disjointness guard at the end of `collectCatalogCards`.
 */
function validatePendingVariants(agent, key) {
  const arr = agent[key];
  if (arr === undefined || arr === null) return;
  assert(Array.isArray(arr),
    `Field "${key}" of agent "${agent.name}" must be an array, got ${typeof arr}`,
    { agentName: agent.name, field: key });
  arr.forEach((item, idx) => {
    assert(item !== null && typeof item === 'object' && !Array.isArray(item),
      `Entry ${idx} of "${key}" for agent "${agent.name}" must be an object`,
      { agentName: agent.name, field: key, idx });
    assert(typeof item.id === 'string' && item.id.length > 0,
      `Entry ${idx} of "${key}" for agent "${agent.name}" is missing required "id" field`,
      { agentName: agent.name, field: key, idx });
  });
}

function validateBaseAgent(agent, index) {
  assert(typeof agent.name === 'string' && agent.name.length > 0,
    `Base agent at index ${index} is missing required "name" field`,
    { index, agent });
  assert(typeof agent.model === 'string' && agent.model.length > 0,
    `Base agent "${agent.name}" is missing required "model" field`,
    { agentName: agent.name });
  assert(typeof agent.description === 'string' && agent.description.trim().length > 0,
    `Base agent "${agent.name}" is missing required non-empty "description" field`,
    { agentName: agent.name });
  if (agent.spawns !== undefined && agent.spawns !== null) {
    assert(typeof agent.spawns === 'string',
      `Base agent "${agent.name}" field "spawns" must be a string, got ${typeof agent.spawns}`,
      { agentName: agent.name, spawns: agent.spawns });
  }
  if (agent.tools) {
    validateTools(agent.tools, agent.name, null);
  }
  assertOptionalArray(agent.capabilities, 'capabilities', agent.name);
  assertOptionalArray(agent.skills, 'skills', agent.name);
  assertOptionalArray(agent.variants, 'variants', agent.name);
  validatePendingVariants(agent, 'pendingVariants');
  validatePendingVariants(agent, 'pending_variants');
}

function validateVariant(variant, agentName, vIndex) {
  assert(typeof variant.id === 'string' && variant.id.length > 0,
    `Variant at index ${vIndex} of agent "${agentName}" is missing required "id" field`,
    { agentName, vIndex, variant });
  assert(typeof variant.model === 'string' && variant.model.length > 0,
    `Variant "${variant.id}" of agent "${agentName}" is missing required "model" field`,
    { agentName, variantId: variant.id });
  if (variant.tools) {
    validateTools(variant.tools, agentName, variant.id);
  }
  if (variant.note !== undefined && variant.note !== null) {
    assert(typeof variant.note === 'string',
      `Variant "${variant.id}" of agent "${agentName}" field "note" must be a string`,
      { agentName, variantId: variant.id });
  }
  assertOptionalArray(variant.systemSections, 'systemSections', `${agentName}/${variant.id}`);
}

