/** Normalize a name to lowercase-kebab for filesystem safety and collision detection. */
function normalize(name) {
  if (typeof name !== 'string' || name.trim().length === 0) {
    throw new SyncError(`Invalid name: "${name}" — must be a non-empty string`);
  }
  const result = name.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
  if (result.length === 0) {
    throw new SyncError(`Name "${name}" normalizes to empty after kebab transformation`);
  }
  return result;
}

/** Validate and translate a tools array. Rejects unknown tool names. */
function validateTools(tools, agentName, variantId) {
  if (!Array.isArray(tools)) {
    throw new SyncError(
      `Tools for "${agentName}${variantId ? ` variant ${variantId}` : ''}" is not an array`,
      { agentName, variantId, tools });
  }
  const translated = [];
  for (const t of tools) {
    if (typeof t !== 'string') {
      throw new SyncError(`Tool entry "${t}" is not a string`, { agentName, variantId, tool: t });
    }
    const mapped = TOOL_TRANSLATION[t];
    if (!mapped) {
      throw new SyncError(
        `Unknown tool "${t}" in agent "${agentName}${variantId ? ` variant ${variantId}` : ''}" — ` +
        `allowed: ${Object.keys(TOOL_TRANSLATION).join(', ')}`,
        { agentName, variantId, tool: t });
    }
    translated.push(mapped);
  }
  return translated;
}

/** Resolve effective tools for a card: variant tools override base tools. */
function resolveTools(agent, variant) {
  const tools = variant?.tools ?? agent.tools;
  if (!tools || tools.length === 0) return undefined;
  return validateTools(tools, agent.name, variant?.id);
}
/** YAML-safe quoting for scalar values from catalog data. */
function yamlSafe(value) {
  return JSON.stringify(String(value ?? ''));
}

/** Resolve effective thinkingLevel. */
function resolveThinkingLevel(agent, variant) {
  return variant?.thinkingLevel ?? agent.thinkingLevel ?? null;
}

/** Resolve effective model string from the catalog. */
function resolveCatalogModel(agent, variant) {
  return variant?.model ?? agent.model;
}

/**
 * Determine if a card qualifies for `task` and `spawns` in OMP.
 * Only roles with explicit spawns in the catalog get these fields. This is
 * scoped to the BASE role only — a variant never carries its own spawns, so
 * `task`/`spawns` on a variant card always mirror the base role's spawns.
 */
function resolveSpawns(agent, _variant) {
  const spawns = agent.spawns;
  if (!spawns) return undefined;
  if (spawns === '*') return '*';
  return spawns.split(',').map(s => s.trim()).filter(Boolean).join(', ');
}

function resolveTask(agent, _variant) {
  return agent.spawns ? true : undefined;
}

