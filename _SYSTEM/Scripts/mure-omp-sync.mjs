// @serves: catalog-to-OMP projection generator — reads _SYSTEM/mure/agent-catalog.json,
//   resolves every active base+variant through omp-model-resolver, writes .omp/agents/*.md,
//   .omp/config.yml, and _SYSTEM/state/mure-omp-projection.json.
// @doctrine: deterministic, collision-free, fail-fast on invalid source items.
//   Every card always carries `model` in frontmatter. Resolver-OK cards use the
//   resolved selector; fail-closed cards use the sentinel `disabled/mure-route-unavailable`
//   so that disabled routes cannot inherit the parent model from stale session settings.
//   Config ownership gate: refuse overwrite unless line 1 is a recognized generator marker.
//   Manifest ownership gate: refuse overwrite unless the JSON carries the provenance marker.
//   Sync is a staged transaction: preflight (validation + symlink safety + strict reads),
//   stage (move every replacement + stale owned card to a same-parent hidden sibling backup), commit
//   (write new content), and on any commit failure roll every staged byte back before
//   surfacing the error. Backups are deleted only once the whole transaction succeeds.
//   --check detects drift (including unowned extras) without ever mutating.
//
// CLI: node _SYSTEM/Scripts/mure-omp-sync.mjs [sync|--check]

