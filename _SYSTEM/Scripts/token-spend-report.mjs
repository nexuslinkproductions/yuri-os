#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveTokenLedgerPaths } from './token-ledger.mjs';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const require = createRequire(path.join(repoRoot, 'backend', 'package.json'));
const Database = require('better-sqlite3');

const DURATIONS = new Map([
  ['1h', '-1 hours'],
  ['24h', '-24 hours'],
  ['7d', '-7 days'],
  ['30d', '-30 days'],
]);

const COST_TRENDS_PATH = path.join(repoRoot, '_SYSTEM', 'cost-trends.md');
const COST_TRENDS_HEADER = `# YURI Token Cost Trends

Daily digest of token spend per lane. Auto-generated by _SYSTEM/Scripts/token-spend-report.mjs --daily-digest.

| Date | Input tokens | Output tokens | Calls | Top 3 lanes (by est. cost USD) |
|---|---|---|---|---|
`;

function parseArgs(argv) {
  const args = { since: '24h', json: false, dailyDigest: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--json') {
      args.json = true;
    } else if (arg === '--daily-digest') {
      args.dailyDigest = true;
      args.since = '24h';
    } else if (arg === '--since') {
      args.since = argv[++i] || '';
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  if (!DURATIONS.has(args.since)) {
    throw new Error(`--since must be one of: ${Array.from(DURATIONS.keys()).join(', ')}`);
  }
  return args;
}

function loadPricing() {
  const configPath = path.join(repoRoot, '.claude', 'config', 'models.json');
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const deepseek = config.deepseek_v4 || {};
  const pricing = deepseek.pricing_per_1m_tokens || {};
  const models = deepseek.models || {};
  const aliases = deepseek.compatibility_aliases || {};
  const byModel = new Map();

  const add = (model, price) => {
    if (model && price) byModel.set(String(model).toLowerCase(), price);
  };

  add(models.flash, pricing.flash);
  add(models.pro, pricing.pro_discounted_until_2026_05_31_15_59_utc);
  add(models.pro_lite_budget, pricing.pro_discounted_until_2026_05_31_15_59_utc);
  for (const [alias, model] of Object.entries(aliases)) {
    const resolved = byModel.get(String(model).toLowerCase());
    add(alias, resolved);
  }

  return byModel;
}

function tableInfo(db, tableName) {
  return db.prepare(`PRAGMA table_info(${tableName})`).all();
}

function resolveSourceTable(db) {
  const tables = new Set(
    db.prepare("SELECT name FROM sqlite_master WHERE type IN ('table', 'view')").all().map((row) => row.name),
  );
  const table = tables.has('token_events') ? 'token_events' : tables.has('token_ledger') ? 'token_ledger' : '';
  if (!table) return null;
  const columns = new Set(tableInfo(db, table).map((row) => row.name));
  const timeColumn = columns.has('recorded_at') ? 'recorded_at' : columns.has('created_at') ? 'created_at' : '';
  if (!timeColumn) return null;
  return { table, timeColumn };
}

function isZeroCost(row) {
  const lane = String(row.lane || '').toLowerCase();
  const model = String(row.request_model || '').toLowerCase();
  return lane.includes('ollama') || lane.includes('codex') || model.startsWith('gpt-5.');
}

function estimateCost(row, pricingByModel) {
  if (isZeroCost(row)) return 0;
  const model = String(row.request_model || '').toLowerCase();
  const pricing = pricingByModel.get(model);
  if (!pricing) return 0;
  return ((row.in_tok * pricing.cache_miss_input) + (row.out_tok * pricing.output)) / 1_000_000;
}

function formatUsd(value) {
  return `$${value.toFixed(6)}`;
}

function formatDigestUsd(value) {
  return `$${value.toFixed(2)}`;
}

function formatInteger(value) {
  return Number(value || 0).toLocaleString('en-US');
}

function todayIsoDate() {
  return new Date().toISOString().slice(0, 10);
}

function buildDigestRow(rows, total) {
  const byLane = new Map();
  for (const row of rows) {
    const lane = row.lane || 'unknown';
    const current = byLane.get(lane) || 0;
    byLane.set(lane, current + row.est_cost_usd);
  }
  const topLanes = Array.from(byLane.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, 3)
    .map(([lane, cost]) => `${lane} (${formatDigestUsd(cost)})`)
    .join(', ') || 'none';

  return `| ${todayIsoDate()} | ${formatInteger(total.in_tokens)} | ${formatInteger(total.out_tokens)} | ${formatInteger(total.calls)} | ${topLanes} |`;
}

function writeDailyDigest(rows, total) {
  const row = buildDigestRow(rows, total);
  const date = todayIsoDate();
  const existing = existsSync(COST_TRENDS_PATH) ? readFileSync(COST_TRENDS_PATH, 'utf8') : COST_TRENDS_HEADER;
  const lines = existing.trimEnd().split('\n');
  const rowPrefix = `| ${date} |`;
  const nextLines = lines.some((line) => line.startsWith(rowPrefix))
    ? lines.map((line) => (line.startsWith(rowPrefix) ? row : line))
    : [...lines, row];
  const nextContent = `${nextLines.join('\n')}\n`;
  const tmpPath = `${COST_TRENDS_PATH}.tmp`;

  mkdirSync(path.dirname(COST_TRENDS_PATH), { recursive: true });
  writeFileSync(tmpPath, nextContent);
  renameSync(tmpPath, COST_TRENDS_PATH);
  console.log(`daily digest written: ${COST_TRENDS_PATH}`);
}

function printTable(rows, total) {
  if (!rows.length) {
    console.log('no token events');
    return;
  }
  const displayRows = rows.map((row) => ({
    lane: row.lane,
    model: row.request_model,
    calls: String(row.calls),
    in_tokens: String(row.in_tokens),
    out_tokens: String(row.out_tokens),
    est_cost_usd: formatUsd(row.est_cost_usd),
  }));
  displayRows.push({
    lane: 'TOTAL',
    model: '',
    calls: String(total.calls),
    in_tokens: String(total.in_tokens),
    out_tokens: String(total.out_tokens),
    est_cost_usd: formatUsd(total.est_cost_usd),
  });

  const columns = ['lane', 'model', 'calls', 'in_tokens', 'out_tokens', 'est_cost_usd'];
  const widths = Object.fromEntries(columns.map((col) => [col, col.length]));
  for (const row of displayRows) {
    for (const col of columns) widths[col] = Math.max(widths[col], row[col].length);
  }
  console.log(columns.map((col) => col.padEnd(widths[col])).join('  '));
  console.log(columns.map((col) => '-'.repeat(widths[col])).join('  '));
  for (const row of displayRows) {
    console.log(columns.map((col) => row[col].padEnd(widths[col])).join('  '));
  }
}

function collectRows(db, source, pricingByModel, since) {
  return db.prepare(`
    SELECT lane, provider, request_model, COUNT(*) as calls,
           SUM(input_tokens) as in_tok, SUM(output_tokens) as out_tok
    FROM ${source.table}
    WHERE ${source.timeColumn} > datetime('now', ?)
    GROUP BY lane, provider, request_model
    ORDER BY in_tok + out_tok DESC
  `).all(DURATIONS.get(since)).map((row) => {
    const normalized = {
      lane: row.lane || '',
      provider: row.provider || '',
      request_model: row.request_model || '',
      calls: Number(row.calls || 0),
      in_tok: Number(row.in_tok || 0),
      out_tok: Number(row.out_tok || 0),
    };
    const estCost = estimateCost(normalized, pricingByModel);
    return {
      lane: normalized.lane,
      model: normalized.request_model,
      request_model: normalized.request_model,
      calls: normalized.calls,
      in_tokens: normalized.in_tok,
      out_tokens: normalized.out_tok,
      est_cost_usd: estCost,
    };
  }).sort((a, b) => b.est_cost_usd - a.est_cost_usd);
}

function totalRows(rows) {
  return rows.reduce((acc, row) => ({
    calls: acc.calls + row.calls,
    in_tokens: acc.in_tokens + row.in_tokens,
    out_tokens: acc.out_tokens + row.out_tokens,
    est_cost_usd: acc.est_cost_usd + row.est_cost_usd,
  }), { calls: 0, in_tokens: 0, out_tokens: 0, est_cost_usd: 0 });
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const { dbPath } = resolveTokenLedgerPaths();
  const pricingByModel = loadPricing();

  if (!existsSync(dbPath)) {
    if (args.dailyDigest) writeDailyDigest([], totalRows([]));
    if (args.json) console.log(JSON.stringify({ rows: [], total: null, message: 'no token events' }, null, 2));
    else console.log('no token events');
    return;
  }

  const db = new Database(dbPath, { readonly: true, fileMustExist: true });
  try {
    const source = resolveSourceTable(db);
    if (!source) {
      if (args.dailyDigest) writeDailyDigest([], totalRows([]));
      if (args.json) console.log(JSON.stringify({ rows: [], total: null, message: 'no token events' }, null, 2));
      else console.log('no token events');
      return;
    }

    const rows = collectRows(db, source, pricingByModel, args.since);
    const total = totalRows(rows);

    if (args.dailyDigest) {
      writeDailyDigest(rows, total);
      return;
    }

    if (args.json) console.log(JSON.stringify({ since: args.since, rows, total }, null, 2));
    else printTable(rows, total);
  } finally {
    db.close();
  }
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
